import { test, expect, type Page } from '@playwright/test'
import { Buffer } from 'node:buffer'
import { setLanguage, t, type Language } from '../../src/i18n'
import type { MessageKey } from '../../src/i18n'

const button = (page: Page, key: MessageKey) => page.getByRole('button', { name: t(key), exact: true })
const card = (page: Page, key: MessageKey) => page.getByRole('region', { name: t(key), exact: true })
const canvas = (page: Page) => page.locator('[data-map-canvas]')
async function projectMenu(page: Page) {
  const trigger = button(page, 'ui.project.menu')
  if (await trigger.getAttribute('aria-expanded') !== 'true') await trigger.click()
}
async function chooseLanguage(page: Page, language: Language) {
  await projectMenu(page)
  await page.getByRole('menuitemradio', { name: language === 'en' ? 'English' : 'Русский', exact: true }).click()
  setLanguage(language, { setItem: () => {} })
  await expect(page.locator('html')).toHaveAttribute('lang', language)
  await button(page, 'ui.project.menu').click()
}
async function menuAction(page: Page, key: MessageKey) {
  await projectMenu(page)
  await page.getByRole('menuitem', { name: t(key), exact: true }).click()
}
async function createProject(page: Page) {
  await menuAction(page, 'ui.projects')
  await page.getByLabel(t('ui.new.project.name'), { exact: true }).fill('Приключение: Проекты, English')
  await button(page, 'ui.create').click()
  await page.getByRole('textbox', { name: t('ui.general.adventure.context'), exact: true }).fill('Пользовательский контекст — never translate')
  await card(page, 'ui.adventure.context').getByRole('button', { name: t('ui.save'), exact: true }).click()
  await expect(card(page, 'ui.adventure.context').getByRole('status')).toHaveText(t('ui.saved.on.this.device'))
  await card(page, 'ui.adventure.context').getByRole('button', { name: t('ui.close.value', { p0: t('ui.adventure.context').toLowerCase() }), exact: true }).click()
  await button(page, 'ui.create.map').click()
  await page.getByLabel(t('ui.new.map.name'), { exact: true }).fill('Карта — user map')
  await page.getByRole('dialog').getByRole('button', { name: t('ui.create.map'), exact: true }).click()
  await expect(canvas(page)).toBeVisible()
}
async function clickPoint(page: Page, x: number, y: number) {
  const box = (await canvas(page).boundingBox())!
  await page.mouse.click(box.x + x, box.y + y)
}
async function camera(page: Page) {
  return page.evaluate(() => {
    const stage = (window as unknown as { Konva: { stages: { x(): number; y(): number; scaleX(): number }[] } }).Konva.stages[0]
    return { x: stage.x(), y: stage.y(), scale: stage.scaleX() }
  })
}

test('language defaults to English, preserves a live editor draft and restores the choice after reload', async ({ page }) => {
  setLanguage('en', { setItem: () => {} })
  await page.goto('/')
  await expect(page.locator('html')).toHaveAttribute('lang', 'en')
  await menuAction(page, 'ui.projects')
  await page.getByLabel(t('ui.new.project.name')).fill('Не переводить — Save')
  await button(page, 'ui.create').click()
  await page.getByRole('textbox', { name: t('ui.general.adventure.context'), exact: true }).fill('Черновик с русским текстом')
  await page.evaluate(() => { (window as unknown as { bmEditor: Element | null }).bmEditor = document.querySelector('.tiptap') })
  await chooseLanguage(page, 'ru')
  await expect(page.getByLabel(t('ui.project.name'), { exact: true })).toHaveValue('Не переводить — Save')
  await expect(page.getByRole('textbox', { name: t('ui.general.adventure.context'), exact: true })).toContainText('Черновик с русским текстом')
  expect(await page.evaluate(() => (window as unknown as { bmEditor: Element }).bmEditor === document.querySelector('.tiptap'))).toBe(true)
  await card(page, 'ui.adventure.context').getByRole('button', { name: t('ui.save'), exact: true }).click()
  await expect(card(page, 'ui.adventure.context').getByRole('status')).toHaveText(t('ui.saved.on.this.device'))
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('lang', 'ru')
  await button(page, 'ui.adventure.context').click()
  await expect(card(page, 'ui.adventure.context')).toContainText('Черновик с русским текстом')
  await chooseLanguage(page, 'en')
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('lang', 'en')
})

