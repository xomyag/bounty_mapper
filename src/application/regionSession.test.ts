async function setup() {
  const factory = new IDBFactory()
  const projects = new ProjectSession(new IndexedDbProjectRepository(() => factory))
  await projects.initialize(); await projects.create('Приключение')
  const image = await new IndexedDbMapImageRepository(() => factory).replace(projects.getSnapshot().project!, testAsset(projects.getSnapshot().project!.id))
  await projects.open(image.project.id)
  const repo = new IndexedDbRegionRepository(() => factory)
  const session = new RegionSession(repo, projects, new IndexedDbModeRepository(() => factory))
  await session.load(image.image.map!.id)
  return { session, projects, repo, mapId: image.image.map!.id }
}
async function create(session: RegionSession) {
  session.start(); session.addPoint({ x: 0, y: 0 }); session.addPoint({ x: 10, y: 0 }); session.addPoint({ x: 10, y: 10 }); session.addPoint({ x: 0, y: 10 }); await session.finish()
}
describe('Region commands and saved history', () => {
  it('moves only the edited region draft; undo/cancel do not write geometry', async () => {
    const { session, repo, mapId } = await setup(); await create(session); await create(session)
    const [a, b] = structuredClone(session.getSnapshot().regions)
    const save = vi.spyOn(repo, 'save')
    session.moveRegionDraft(a.id, { x: 5, y: 3 })
    expect(session.hasUnsavedDetails()).toBe(false)
    session.openCard(a.id); session.moveRegionDraft(b.id, { x: 5, y: 3 })
    expect(session.hasUnsavedDetails()).toBe(false)
    session.moveRegionDraft(a.id, { x: 5, y: 3 }); session.moveRegionDraft(a.id, { x: 2, y: 4 })
    expect(session.getSnapshot().details[a.id].fields.vertices).toEqual(translateVertices(a.vertices, { x: 7, y: 7 }))
    await session.undo()
    expect(session.getSnapshot().details[a.id].fields.vertices).toEqual(translateVertices(a.vertices, { x: 5, y: 3 }))
    await session.redo()
    expect(save).not.toHaveBeenCalled()
    expect(await repo.load(mapId)).toEqual([a, b])
    session.cancelEdit(); session.moveRegionDraft(a.id, { x: 5, y: 3 })
    expect(session.hasUnsavedDetails()).toBe(false)
    expect(session.getSnapshot().regions).toEqual([a, b])
  })
  it('saves geometry and content atomically and retains failed drafts/destination', async () => {
    const { session, repo, mapId } = await setup(); await create(session); await create(session)
    const [a, b] = structuredClone(session.getSnapshot().regions)
    session.openCard(a.id); session.moveRegionDraft(a.id, { x: 5, y: 3 })
    session.editDetails(a.id, { ...session.getSnapshot().details[a.id].fields, title: 'Новая комната' })
    session.openCard(b.id)
    expect(session.getSnapshot().pendingIntent).toEqual({ kind: 'open', id: b.id })
    vi.spyOn(repo, 'save').mockRejectedValueOnce(new Error('Нет места'))
    await session.resolveCardIntent('save')
    expect(await repo.load(mapId)).toEqual([a, b])
    expect(session.getSnapshot().details[a.id]).toMatchObject({ phase: 'error', fields: { title: 'Новая комната', vertices: translateVertices(a.vertices, { x: 5, y: 3 }) } })
    expect(session.getSnapshot().cardId).toBe(a.id)
    await session.resolveCardIntent('save')
    expect(session.getSnapshot().cardId).toBe(b.id)
    expect((await repo.load(mapId))[0]).toMatchObject({ title: 'Новая комната', vertices: translateVertices(a.vertices, { x: 5, y: 3 }) })
    session.cancelEdit(); await session.undo()
    expect((await repo.load(mapId))[0]).toMatchObject({ title: 'Новая комната', vertices: a.vertices })
    await session.redo()
    session.requestMode('play'); await new Promise((resolve) => setTimeout(resolve, 0))
    session.moveRegionDraft(a.id, { x: 999, y: 999 })
    expect((await repo.load(mapId))[0].vertices).toEqual(translateVertices(a.vertices, { x: 5, y: 3 }))
  })
  it('opens empty regions for editing, uses saved view for filled regions and ignores technical blocks/number/color', async () => {
    const { session, repo, mapId } = await setup(); await create(session)
    const a = session.getSnapshot().regions[0]
    session.openCard(a.id)
    expect(session.getSnapshot().cardMode).toBe('edit')
    expect(session.hasUnsavedDetails()).toBe(false)
    session.editDetails(a.id, { ...detailsOf(a), number: '7', color: '#ef6543', gmNotes: emptyDocument() })
    await session.saveDetails(); session.closeCard(); session.openCard(a.id)
    expect(session.getSnapshot().cardMode).toBe('edit')
    const fields = session.getSnapshot().details[a.id].fields
    session.editDetails(a.id, { ...fields, gmNotes: markdownToDocument('# Зал\n**Тайна**') })
    await session.saveDetails(); session.closeCard(); session.openCard(a.id)
    expect(session.getSnapshot().cardMode).toBe('view')
    expect((await repo.load(mapId))[0].gmNotes).toEqual(markdownToDocument('# Зал\n**Тайна**'))
  })
  it('prompts on closing/switching a dirty card; stay/discard/save apply only to its region', async () => {
    const { session, repo, mapId } = await setup(); await create(session); await create(session)
    const [a, b] = session.getSnapshot().regions
    session.openCard(a.id)
    session.editDetails(a.id, { ...detailsOf(a), title: 'Мой зал', gmNotes: markdownToDocument('Черновик A') })
    session.openCard(b.id)
    expect(session.getSnapshot()).toMatchObject({ cardId: a.id, pendingIntent: { kind: 'open', id: b.id } })
    await session.resolveCardIntent('stay')
    expect(localize(session.getSnapshot().details[a.id].fields.title)).toBe('Мой зал')
    expect((await repo.load(mapId))[0].title).toBe(a.title)
    session.openCard(b.id); await session.resolveCardIntent('save')
    expect(session.getSnapshot()).toMatchObject({ cardId: b.id, cardMode: 'edit' })
    expect(localize((await repo.load(mapId)).find((r) => r.id === a.id)?.title)).toBe('Мой зал')
    session.editDetails(b.id, { ...detailsOf(b), gmNotes: markdownToDocument('Отбросить B') })
    session.closeCard(); await session.resolveCardIntent('discard')
    expect(session.getSnapshot().cardId).toBeUndefined()
    expect((await repo.load(mapId)).find((r) => r.id === b.id)?.gmNotes).toEqual(emptyDocument())
  })
  it('keeps the draft and pending destination on a write error; rejects export and retries explicitly', async () => {
    const { session, repo, mapId } = await setup(); await create(session)
    const a = session.getSnapshot().regions[0]
    session.openCard(a.id); session.editDetails(a.id, { ...detailsOf(a), gmNotes: markdownToDocument('Не потерять') })
    await expect(localizedFailure(session.flushDetails())).rejects.toThrow('Сначала сохраните')
    session.closeCard()
    vi.spyOn(repo, 'save').mockRejectedValueOnce(new Error('Нет места'))
    await session.resolveCardIntent('save')
    expect(session.getSnapshot()).toMatchObject({ cardId: a.id, pendingIntent: { kind: 'close' }, details: { [a.id]: { phase: 'error', error: 'Нет места' } } })
    expect((await repo.load(mapId))[0].gmNotes).toEqual(emptyDocument())
    await session.resolveCardIntent('stay'); await session.saveDetails()
    expect(session.getSnapshot().cardMode).toBe('view')
    expect((await repo.load(mapId))[0].gmNotes).toEqual(markdownToDocument('Не потерять'))
  })
  it('preserves later documents through geometry undo/redo and cancels all draft fields together', async () => {
    const { session, repo, mapId } = await setup(); await create(session)
    const a = session.getSnapshot().regions[0]
    await session.change({ ...a, vertices: translateVertices(a.vertices, { x: 20, y: 10 }) })
    session.openCard(a.id); session.editDetails(a.id, { ...session.getSnapshot().details[a.id].fields, gmNotes: markdownToDocument('Описание'), title: 'Зал' })
    await session.saveDetails(); await session.undo()
    expect((await repo.load(mapId))[0]).toMatchObject({ vertices: a.vertices, gmNotes: markdownToDocument('Описание'), title: 'Зал' })
    await session.redo(); session.beginEdit()
    const saved = structuredClone(session.getSnapshot().regions[0])
    session.editDetails(a.id, { ...detailsOf(saved), title: 'Отмена', color: '#ff0000', tags: ['новый'], checks: [{ id: '1', condition: 'Новая', ability: '', result: '' }] })
    session.cancelEdit()
    expect(session.hasUnsavedDetails()).toBe(false)
    expect((await repo.load(mapId))[0]).toEqual(saved)
  })
  it('keeps edits bound to their ID during a delayed write and does not insert a written asset twice', async () => {
    const { session, repo, projects, mapId } = await setup(); await create(session); await create(session)
    const [a, b] = session.getSnapshot().regions
    session.openCard(a.id)
    const asset = { ...testAsset(projects.getSnapshot().project!.id), id: 'inline', checksum: 'a'.repeat(64) }
    session.addDraftAsset(a.id, asset)
    const gmNotes = { type: 'doc' as const, content: [{ type: 'image', attrs: { assetId: asset.id, alt: '' } }] }
    session.editDetails(a.id, { ...detailsOf(a), gmNotes, title: 'Первая версия' })
    let release!: () => void
    const gate = new Promise<void>((resolve) => { release = resolve })
    const save = repo.save.bind(repo)
    const spy = vi.spyOn(repo, 'save').mockImplementationOnce(async (...args) => { await gate; return save(...args) })
    const writing = session.saveDetails()
    session.openCard(b.id); session.closeCard()
    expect(session.getSnapshot().cardId).toBe(a.id)
    session.editDetails(a.id, { ...session.getSnapshot().details[a.id].fields, title: 'Последняя версия' })
    release(); await writing
    expect(session.getSnapshot().details[a.id]?.error).toBeUndefined()
    expect(session.hasUnsavedDetails()).toBe(false)
    expect(session.getSnapshot().cardMode).toBe('view')
    expect(spy).toHaveBeenCalledTimes(2)
    expect(spy.mock.calls[1][3]).toEqual([])
    const rows = await repo.load(mapId)
    expect(rows.find((r) => r.id === a.id)).toMatchObject({ title: 'Последняя версия', gmNotes })
    expect(rows.find((r) => r.id === b.id)).toEqual(b)
  })
  it('moves and removes draft vertices without storage/history writes until valid completion', async () => {
    const { session, projects, repo, mapId } = await setup()
    const revision = projects.getSnapshot().project!.revision
    const save = vi.spyOn(repo, 'save')
    session.start()
    for (const point of [{ x: 0, y: 0 }, { x: 10, y: 0 }, { x: 10, y: 10 }, { x: 0, y: 10 }]) session.addPoint(point)
    session.moveDraftVertex(0, { x: -2, y: 1 })
    session.removeDraftVertex(1)
    const edited = structuredClone(session.getSnapshot().draft)
    session.moveDraftVertex(-1, { x: 100, y: 100 }); session.removeDraftVertex(99)
    expect(session.getSnapshot().draft).toEqual(edited)
    expect(await repo.load(mapId)).toEqual([])
    expect(save).not.toHaveBeenCalled()
    expect(projects.getSnapshot().project!.revision).toBe(revision)
    expect(session.getSnapshot().canUndo).toBe(false)
    await session.finish()
    expect((await repo.load(mapId))[0].vertices).toEqual([{ x: -2, y: 1 }, { x: 10, y: 10 }, { x: 0, y: 10 }])
    expect(save).toHaveBeenCalledTimes(1)
    await session.undo()
    expect(await repo.load(mapId)).toEqual([])
  })
  it('allows deleting all draft vertices and invalidates a failed creation retry when the draft changes', async () => {
    const { session, repo, mapId } = await setup()
    vi.spyOn(repo, 'save').mockRejectedValueOnce(new Error('Нет места'))
    await create(session)
    expect(session.getSnapshot().canRetry).toBe(true)
    session.moveDraftVertex(0, { x: -1, y: 1 })
    expect(session.getSnapshot().canRetry).toBe(false)
    await session.retry()
    expect(await repo.load(mapId)).toEqual([])
    await session.finish()
    expect((await repo.load(mapId))[0].vertices[0]).toEqual({ x: -1, y: 1 })
    session.start(); session.addPoint({ x: 1, y: 2 }); session.removeDraftVertex(0)
    expect(session.getSnapshot().draft).toEqual([])
    await session.finish()
    expect(localize(session.getSnapshot().error)).toContain('три')
    session.cancel()
    expect(await repo.load(mapId)).toHaveLength(1)
  })
  it('removes the requested saved vertex as one undoable command, retaining at least three', async () => {
    const { session, repo, mapId } = await setup()
    await create(session)
    const original = structuredClone(session.getSnapshot().regions[0])
    session.setVertexMode(true); session.selectVertex(2)
    await session.removeVertex(0)
    expect((await repo.load(mapId))[0].vertices).toEqual(original.vertices.slice(1))
    await session.removeVertex(1)
    expect(localize(session.getSnapshot().error)).toContain('минимум три')
    expect((await repo.load(mapId))[0].vertices).toEqual(original.vertices.slice(1))
    await session.undo()
    expect(await repo.load(mapId)).toEqual([original])
    await session.redo()
    expect((await repo.load(mapId))[0].vertices).toEqual(original.vertices.slice(1))
  })
  it('never writes an unfinished, cancelled or invalid contour; suppresses a repeated last vertex', async () => {
    const { session, repo, mapId } = await setup()
    session.start(); session.addPoint({ x: 0, y: 0 }); session.addPoint({ x: 0, y: 0 }); session.addPoint({ x: 1, y: 1 })
    expect(session.getSnapshot().draft).toHaveLength(2)
    await session.finish()
    expect(localize(session.getSnapshot().error)).toContain('три')
    expect(await repo.load(mapId)).toEqual([])
    session.cancel()
    expect(session.getSnapshot().draft).toBeUndefined()
    expect(session.getSnapshot().canUndo).toBe(false)
  })
  it('undoes/redoes creation, one completed drag, vertex edits and deletion; new commands clear redo', async () => {
    const { session, repo, mapId } = await setup()
    await create(session)
    const original = structuredClone(session.getSnapshot().regions[0])
    expect(original.fillOpacity).toBe(0.4)
    const moved = { ...original, vertices: translateVertices(original.vertices, { x: -25, y: 13 }) }
    await session.change(moved)
    await session.undo(); expect(await repo.load(mapId)).toEqual([original])
    await session.redo(); expect(await repo.load(mapId)).toEqual([moved])
    session.setVertexMode(true); session.selectVertex(0); await session.removeVertex()
    expect(session.getSnapshot().regions[0].vertices).toHaveLength(3)
    session.selectVertex(0); await session.removeVertex()
    expect(session.getSnapshot().regions[0].vertices).toHaveLength(3)
    await session.undo(); expect(session.getSnapshot().regions).toEqual([moved])
    await session.remove(); expect(await repo.load(mapId)).toEqual([])
    await session.undo(); expect(session.getSnapshot().regions).toEqual([moved])
    await session.undo(); expect(session.getSnapshot().regions).toEqual([original])
    await session.undo(); expect(session.getSnapshot().regions).toEqual([])
    await session.redo(); expect(session.getSnapshot().regions).toEqual([original])
    await session.change({ ...original, title: 'Новое название' })
    expect(session.getSnapshot().canRedo).toBe(false)
  })
  it('reports saved only after transaction completion; keeps geometry/history on failure and retries', async () => {
    const { session, projects, repo } = await setup()
    await create(session)
    const original = structuredClone(session.getSnapshot().regions)
    const changed = { ...original[0], vertices: translateVertices(original[0].vertices, { x: 2, y: -3 }) }
    const save = repo.save.bind(repo)
    let finish!: () => void
    vi.spyOn(repo, 'save').mockImplementationOnce((...args) => new Promise((resolve, reject) => { finish = () => { void save(...args).then(resolve, reject) } }))
    const writing = session.change(changed)
    expect(session.getSnapshot().phase).toBe('saving')
    expect(projects.getSnapshot().loading).toBe(true)
    await expect(projects.open('other')).rejects.toThrow()
    finish(); await writing
    expect(session.getSnapshot().phase).toBe('saved')
    vi.spyOn(repo, 'save').mockRejectedValueOnce(new Error('Тестовая ошибка записи'))
    await session.undo()
    expect(session.getSnapshot()).toMatchObject({ phase: 'error', regions: [changed], canUndo: true, canRedo: false, canRetry: true })
    await session.retry()
    expect(session.getSnapshot()).toMatchObject({ phase: 'saved', regions: original, canRedo: true })
  })
  it('keeps a failed creation draft and can retry; drops history and selection on switching/reloading', async () => {
    const { session, repo, mapId } = await setup()
    vi.spyOn(repo, 'save').mockRejectedValueOnce(new Error('Нет места'))
    await create(session)
    expect(session.getSnapshot()).toMatchObject({ phase: 'error', regions: [], canUndo: false })
    expect(session.getSnapshot().draft).toHaveLength(4)
    await session.retry()
    expect(session.getSnapshot().draft).toBeUndefined()
    await session.load(mapId)
    expect(session.getSnapshot()).toMatchObject({ phase: 'saved', canUndo: false, canRedo: false, selectedId: undefined })
    expect(session.getSnapshot().regions).toHaveLength(1)
  })
  it('ignores stale reads and prevents overwriting regions after a failed read', async () => {
    const { session, repo, mapId } = await setup()
    let resolve!: (regions: never[]) => void
    vi.spyOn(repo, 'load').mockImplementationOnce(() => new Promise((r) => { resolve = r }))
    const old = session.load('old-map')
    await session.load(mapId); resolve([]); await old
    expect(session.getSnapshot().mapId).toBe(mapId)
    vi.spyOn(repo, 'load').mockRejectedValueOnce(new Error('Ошибка чтения'))
    await session.load(mapId)
    session.start()
    expect(session.getSnapshot().draft).toBeUndefined()
    await session.retry(); expect(session.ready()).toBe(true)
  })
})
